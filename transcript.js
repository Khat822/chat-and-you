// ============================================
// CHAT. AND YOU. - conversation export (classic script)
// Builds a self-explaining Markdown file: what the app is, every turn with
// the options that were shown, the final ticket, and a review task, so any
// AI (or human) can give a second opinion without knowing this app.
// ============================================
(() => {
    'use strict';
    if (window.CAY_TRANSCRIPT) return;

    const KIND = {
        asking: 'AI reply',
        reply: 'AI reply',
        ready: 'AI reply',
        clarify: 'AI asked again: it was unsure what the previous answer meant',
        offmenu: 'refused: off-limits topic, answered with a playful "try another one"',
        care: 'care message about safety or self-harm (no jokes)',
        scripted: 'pre-written line (not generated by AI)',
        menu: 'local menu, not AI',
        blocked: 'AI Studio\'s own safety filter blocked the reply (often a false alarm); the same options were shown again',
        plainer: 'pre-written reassurance after "Wait, what?" (demo, not AI)',
        'bridge-error': 'technical problem talking to AI Studio, not the companion\'s opinion'
    };

    const HOWTO = '> **For the human:** paste this whole file into any AI assistant (Kiro, Gemini, ChatGPT, ...) and ask: "Please review this and give me a better prompt."';

    const BRIEF = `This is an exported conversation from **CHAT. AND YOU.**, a small web app where a pixel-art cat or dog companion helps someone who is not a prompt expert turn a fuzzy wish into a clear prompt.

How the conversation works:
- **Canteen mode** (the important part): in about 3 short rounds the companion asks what the user wants to make, what the finished result should look like, and the single most important rule. Users may also just play or chat: that is valid, and a silly wish may be built for real. When there is something to build it hands over a **Kiro Order Ticket**: a structured prompt with Summary, Input, Output, Constraints, Avoid and Done when (checks the companion wrote itself; the user was not asked for them), meant to be pasted into Kiro, Gemini or GPT.
- **Every turn** shows one short companion message and three options A, B and C written by the companion. **D** is a free-text box where the user writes in their own words. **D answers are the strongest signal of what the user really wants**; A/B/C may have been picked just because they were "close enough". The user can also pick several options at once (shown as "A+C", texts joined with " + "), optionally with their own words.
- **Campfire mode** is a light fantasy story game using the same A/B/C/D loop. It does not produce a ticket, and it follows different instructions than the canteen (see the appendices).
- The companion has a playful personality. In "Catnip / Squeaky Ball" mode it adds animal noises (meow, woof, ...) on purpose: ignore them, they carry no meaning.
- "Assumption: ..." inside the ticket means the companion guessed after the user's answers stayed unclear.`;

    const TASK = `1. In one or two sentences, say what the user actually wants.
2. List the turns (by number) where an answer was ambiguous, contradicted an earlier one, or where the companion misread the user. Quote the words.
3. Check the Kiro Order Ticket against the conversation: what is missing, wrong, too vague, or invented (not supported by anything the user said)?
4. If something important is still unclear, ask the user at most 3 short questions.
5. Write an improved ticket with the same sections: Summary, Input, Output, Constraints, Avoid, Done when (plain pass/fail checks a non-expert understands). Keep it plain and copy-paste ready.

Reply in the language the user wrote in.`;

    const TICKET = [['summary', 'Summary'], ['input', 'Input'], ['output', 'Output'], ['constraints', 'Constraints'], ['antipatterns', 'Avoid'], ['done', 'Done when']];
    const quote = (s) => String(s ?? '').split('\n').map(l => `> ${l}`).join('\n');
    const modeName = (m) => m === 'campfire' ? 'Campfire' : 'Canteen';

    function build(entries, meta) {
        const out = [
            '# CHAT. AND YOU. - conversation export', '', HOWTO, '',
            '## What this file is (read this first)', '', BRIEF, '',
            '## Session', '',
            `- Exported: ${meta.date}`,
            `- Where it ran: ${meta.where}`,
            `- Companion: ${meta.companion}`,
            `- Interface language: ${meta.language}`,
            `- Humor level: ${meta.spice}`,
            `- Catnip / Squeaky Ball mode at export time: ${meta.euphoria ? 'on' : 'off'}`,
            '', '## Conversation'
        ];
        let turn = 0, open = false, tickets = 0;
        for (const e of entries) {
            if (e.role === 'event') {
                out.push('', `*--- ${e.text} ---*`);
                open = false;
            } else if (e.role === 'companion') {
                turn++; open = true;
                out.push('', `### Turn ${turn} (${modeName(e.mode)}${e.euphoria ? ', catnip/ball mode on' : ''})`, '',
                    `**Companion** (${KIND[e.kind] || e.kind}):`, quote(e.message));
                if (e.options?.length) {
                    out.push('', 'Options shown:');
                    e.options.forEach((o, i) => out.push(`- **${'ABC'[i]}**: ${o}`));
                    out.push('- **D**: free-text box ("write it myself")');
                }
            } else if (e.role === 'user') {
                if (!open) { turn++; out.push('', `### Turn ${turn} (${modeName(e.mode)})`); }
                out.push('', e.choice === 'huh'
                    ? `**User tapped "Wait, what?"** (didn't understand the last message; not an answer): ${e.text}`
                    : e.choice === 'serve'
                    ? `**User tapped "That's enough, serve it"** (skipped the remaining questions): ${e.text}`
                    : e.choice === 'd'
                    ? `**User wrote (D, own words):** "${e.text}"`
                    : `**User picked ${e.choice.toUpperCase()}:** ${e.text}`);
                open = false;
            } else if (e.role === 'ticket') {
                tickets++;
                out.push('', `## Kiro Order Ticket #${tickets} (the output to review)`, '');
                TICKET.forEach(([k, title]) => out.push(`**${title}:** ${e.fields?.[k] || '-'}`, ''));
                open = false;
            }
        }
        if (!tickets) out.push('', '_No Kiro Order Ticket was produced in this session._');
        for (const p of meta.primers || []) {
            out.push('', `## Appendix: instructions given to Gemini in ${p.mode} mode`, '',
                `These apply to ${p.mode} turns only; each mode has its own rules. Rebuilt with the settings at export time, so moods toggled mid-session and the opener may differ slightly.`, '',
                '```text', p.text, '```');
        }
        out.push('', '## Your task as reviewer', '', TASK, '');
        return out.join('\n');
    }

    function download(text, filename) {
        // BOM so Windows editors detect UTF-8 (Chinese, Japanese, ...)
        const blob = new Blob(['\uFEFF' + text], { type: 'text/markdown;charset=utf-8' });
        const url = URL.createObjectURL(blob);
        const a = Object.assign(document.createElement('a'), { href: url, download: filename });
        (document.body || document.documentElement).appendChild(a);
        a.click();
        a.remove();
        setTimeout(() => URL.revokeObjectURL(url), 1000);
    }

    window.CAY_TRANSCRIPT = { build, download };
})();
